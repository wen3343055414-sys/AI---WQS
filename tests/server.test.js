import test from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, rm, stat } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { spawn } from "node:child_process";
import { once } from "node:events";
import { WorkspaceStore } from "../src/store.js";
import { createInitialState } from "../public/core.js";

test("服务器登录、乐观锁、备份与重启后持久保存", { timeout: 20000 }, async t => {
  const directory = await mkdtemp(path.join(tmpdir(), "wqs-api-"));
  let child;
  const stop = async () => { if (child && child.exitCode === null && child.signalCode === null) { const exited = once(child, "exit"); child.kill(); await exited; } };
  t.after(async () => { await stop(); await rm(directory, { recursive: true, force: true }); });
  const start = async () => {
    child = spawn(process.execPath, ["src/server.js"], { env: { ...process.env, HOST: "127.0.0.1", PORT: "0", DATA_DIR: directory, APP_VERSION: "test-release" }, stdio: ["ignore", "pipe", "pipe"] });
    return new Promise((resolve, reject) => {
      const timer = setTimeout(() => reject(new Error("Server startup timeout")), 5000);
      child.stdout.on("data", data => { const match = String(data).match(/http:\/\/127\.0\.0\.1:\d+/); if (match) { clearTimeout(timer); resolve(match[0]); } });
      child.once("error", reject);
      child.once("exit", code => { clearTimeout(timer); if (code) reject(new Error(`Server exited: ${code}`)); });
    });
  };
  let base = await start();
  const request = (url, { cookie, body, ...options } = {}) => fetch(`${base}${url}`, { signal: AbortSignal.timeout(5000), ...options, headers: { ...(cookie ? { Cookie: cookie } : {}), ...(body !== undefined ? { "Content-Type": "application/json" } : {}), ...options.headers }, ...(body !== undefined ? { body: JSON.stringify(body) } : {}) });
  let status = await (await request("/api/status")).json();
  assert.equal(status.setupRequired, true);
  assert.equal(status.version, "test-release");
  const instance = status.serverId;
  assert.equal((await request("/api/workspace")).status, 401);
  assert.equal((await request("/api/setup", { method: "POST", body: { password: "testing-password-123" }, headers: { Origin: "https://example.invalid" } })).status, 403);
  assert.equal((await request("/api/login", { method: "POST", body: null })).status, 400);
  const setup = await request("/api/setup", { method: "POST", body: { password: "testing-password-123" } });
  assert.equal(setup.status, 200);
  assert.match(setup.headers.get("set-cookie"), /HttpOnly; SameSite=Strict/);
  const cookie = setup.headers.get("set-cookie").split(";")[0];
  assert.equal((await request("/api/setup", { method: "POST", body: { password: "testing-password-123" } })).status, 409);
  const state = createInitialState();
  state.prompts[0].title = "数据库中的工作周报";
  let response = await request("/api/workspace", { method: "PUT", cookie, body: { state, baseRevision: 0 } });
  assert.equal(response.status, 200);
  assert.equal((await response.json()).revision, 1);
  response = await request("/api/workspace", { method: "PUT", cookie, body: { state: createInitialState(), baseRevision: 0 } });
  assert.equal(response.status, 409);
  assert.equal((await response.json()).state.prompts[0].title, "数据库中的工作周报");
  assert.equal((await request("/api/workspace", { method: "PUT", cookie, body: { state: {}, baseRevision: 1 } })).status, 400);
  const store = new WorkspaceStore(directory);
  const snapshot = await store.snapshot();
  store.close();
  assert.ok((await stat(path.join(directory, "backups", snapshot))).size > 0);
  await stop(); base = await start();
  status = await (await request("/api/status", { cookie })).json();
  assert.equal(status.serverId, instance);
  assert.equal(status.authenticated, true);
  const restored = await (await request("/api/workspace", { cookie })).json();
  assert.equal(restored.revision, 1);
  assert.equal(restored.state.prompts[0].title, "数据库中的工作周报");
  assert.equal((await request("/api/login", { method: "POST", body: { password: "incorrect" } })).status, 401);
  const login = await request("/api/login", { method: "POST", body: { password: "testing-password-123" } });
  assert.equal(login.status, 200);
  const second = login.headers.get("set-cookie").split(";")[0];
  assert.equal((await request("/api/workspace", { cookie: second })).status, 200);
  await request("/api/logout", { method: "POST", cookie: second });
  assert.equal((await request("/api/workspace", { cookie: second })).status, 401);
  assert.equal((await request("/api/workspace", { cookie })).status, 200);
});
